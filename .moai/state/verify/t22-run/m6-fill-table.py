src = io.open(P, encoding='utf-8').read().split('\n')
out = []
filled = []
for line in src:
    s = line.strip()
    hit = None
    if s.startswith('|'):
        first = s.split('|')[1].strip().strip('*').strip()
        if first in OBS:
            hit = first
    if hit:
        cells = line.split('|')
        # cells: ['', ' A ', ' 변이 ', ' 예측 ', ' 실측 ', ' 이유 ', '']
        assert (cells[4].strip() == '' or 'run 이 채운다' in cells[4]) and cells[5].strip() == '', line[:60]
        real, why = OBS[hit]
        cells[4] = f' {real} '
        cells[5] = f' {why} '
        out.append('|'.join(cells))
        filled.append(hit)
    else:
        out.append(line)
io.open(P, 'w', encoding='utf-8').write('\n'.join(out))
print('filled rows:', len(filled))
missing = set(OBS) - set(filled)
print('missing:', missing if missing else 'none')
